#!/usr/bin/env python3
"""gen_installer_ja.py - render the Japanese texts of the on-device installer to bitmaps.

The PSP debug font only has ASCII, so psp/installer/installer_text.h keeps the Japanese column as source text and this script
turns it into psp/installer/text_ja.inc (1 bit per pixel, 18 pixel tall lines, wrapped to fit the 480 pixel screen).
The generated file is committed: nobody needs to run this unless a Japanese text changes.

    python3 tools/psp/gen_installer_ja.py [--font NotoSansCJK-Medium.ttc] [--preview preview.png]

Needs Pillow and a Japanese font (the output was made with Noto Sans CJK JP, SIL Open Font License 1.1).
"""
import argparse
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

LINE_H = 18          # glyphs of a 15 px font use ~18 rows including descenders
TOP = -4             # the font leaves ~4 empty rows above the glyphs
MAX_W = 456
NO_LINE_START = "。、）」！？：）"

LITERAL = r'"((?:[^"\\]|\\.)*)"'
ROW = re.compile(r"X\(\s*(\w+)\s*,\s*" + r",\s*".join([LITERAL] * 6) + r"\s*\)")


def unescape(s):
    return bytes(s, "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8") if "\\" in s else s


def wrap(font, text):
    lines, cur = [], ""
    for ch in text:
        if cur and font.getlength(cur + ch) > MAX_W and ch not in NO_LINE_START:
            lines.append(cur)
            cur = ""
        cur += ch
    if cur:
        lines.append(cur)
    return lines


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.normpath(os.path.join(here, "..", ".."))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", default="/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc")
    ap.add_argument("--index", type=int, default=0, help="face index inside a .ttc (0 = Japanese for Noto Sans CJK)")
    ap.add_argument("--header", default=os.path.join(repo, "psp", "installer", "installer_text.h"))
    ap.add_argument("--out", default=os.path.join(repo, "psp", "installer", "text_ja.inc"))
    ap.add_argument("--preview")
    args = ap.parse_args()

    rows = ROW.findall(open(args.header, encoding="utf-8").read().replace("\\\n", " "))
    if not rows:
        sys.exit("no messages found in " + args.header)
    font = ImageFont.truetype(args.font, 15, index=args.index)

    data, index, preview = bytearray(), [], []
    for row in rows:
        name, text = row[0], unescape(row[6])
        lines = wrap(font, text)
        w = max(int(font.getlength(l)) + 1 for l in lines)
        gray = Image.new("L", (w, LINE_H * len(lines)), 0)
        d = ImageDraw.Draw(gray)
        for i, l in enumerate(lines):
            d.text((0, i * LINE_H + TOP), l, font=font, fill=255)
        # anti-aliased render, then a low threshold: keeps thin strokes and dots (dakuten, 。) that a plain 1-bit render drops
        img = gray.point(lambda v: 255 if v >= 80 else 0).convert("1")
        rb = (w + 7) // 8
        index.append((len(data), w, img.height, name))
        px = img.load()
        for y in range(img.height):
            for bx in range(rb):
                b = 0
                for k in range(8):
                    x = bx * 8 + k
                    b = (b << 1) | (1 if x < w and px[x, y] else 0)
                data.append(b)
        preview.append(img)
    if len(data) > 0xFFFF:
        sys.exit("bitmap data too large for 16 bit offsets")

    with open(args.out, "w") as f:
        f.write("/* Generated by tools/psp/gen_installer_ja.py from psp/installer/installer_text.h. Do not edit.\n"
                " * Glyphs rendered from Noto Sans CJK JP (SIL Open Font License 1.1). */\n")
        f.write("#define JA_MESSAGE_COUNT %d\n" % len(index))
        f.write("static const unsigned char ja_data[%d] = {\n" % len(data))
        for i in range(0, len(data), 24):
            f.write("    " + ",".join("0x%02X" % b for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
        f.write("/* offset, width, height in pixels, one per message in the order of SMI_MESSAGES */\n")
        f.write("static const struct { unsigned short off, w, h; } ja_index[JA_MESSAGE_COUNT] = {\n")
        for off, w, h, name in index:
            f.write("    { %d, %d, %d }, /* %s */\n" % (off, w, h, name))
        f.write("};\n")
    print("wrote %s: %d messages, %d bytes of bitmap data" % (args.out, len(index), len(data)))

    if args.preview:
        total = sum(i.height + 4 for i in preview)
        sheet = Image.new("L", (480, total), 0)
        y = 0
        for img in preview:
            sheet.paste(img.convert("L").point(lambda v: 255 if v else 0), (0, y))
            y += img.height + 4
        sheet.save(args.preview)


if __name__ == "__main__":
    main()
